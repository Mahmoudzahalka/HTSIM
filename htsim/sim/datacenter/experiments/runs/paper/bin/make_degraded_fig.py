#!/usr/bin/env python3
"""Degraded-link figure + table numbers for the paper.

Reads degraded_links/*/rows/*.row (seed 13, 128 nodes, 1:1 fat-tree) and writes
figs/fig_degraded.pdf and degraded_table.tex. Colours follow the H100 deck
(Okabe-Ito per workload) so the paper's figures read as one set."""
import glob, os, collections
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
ROWS = os.path.join(PAPER, "..", "degraded_links", "*", "rows", "*.row")

d = collections.defaultdict(dict)  # (wl,size,stack) -> level -> makespan
for f in glob.glob(ROWS):
    r = open(f).read().strip().split(",")
    if r[10] != "ok":
        continue
    lvl = r[7].split(".")[1]
    d[(r[2], int(r[3]), r[6])][lvl] = float(r[14])

LEVELS = ["base", "r50", "r25", "r10"]
XLAB = ["none\n(400G)", "50%\n(200G)", "25%\n(100G)", "10%\n(40G)"]
WL = [("perm_random", "#0072B2", "o"), ("perm_fullbis", "#56B4E9", "s"),
      ("incast_random", "#D55E00", "^"), ("incast_remote", "#E69F00", "v"),
      ("outcast_incast", "#CC79A7", "D")]
STACKS = [("ib", "RoCE + DCQCN", "#0072B2"), ("uet", "UET", "#D55E00")]

plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6), sharey=True)
for ax, (stk, title, tcol) in zip(axes, STACKS):
    for wl, col, mk in WL:
        # line = 64 MB; shaded band = min..max over 16/64/100 MB
        ys = [[d[(wl, s, stk)][l] / d[(wl, s, stk)]["base"] for l in LEVELS] for s in (16, 64, 100)]
        lo = [min(v[i] for v in ys) for i in range(4)]
        hi = [max(v[i] for v in ys) for i in range(4)]
        ax.fill_between(range(4), lo, hi, color=col, alpha=0.18, linewidth=0)
        ax.plot(range(4), ys[1], color=col, marker=mk, ms=5, lw=2, label=wl)
    ax.set_yscale("log")
    ax.set_xticks(range(4)); ax.set_xticklabels(XLAB)
    ax.set_title(title, color=tcol, fontweight="bold")
    ax.axhline(1, color="#888888", lw=0.8, zorder=0)
    ax.minorticks_off(); ax.grid(axis="y", which="major", color="#e5e5e5", lw=0.6)
    ax.set_xlabel("speed retained by the degraded link")
axes[0].set_ylabel("makespan ÷ healthy fabric (log)")
axes[0].set_yticks([1, 2, 4, 8]); axes[0].set_yticklabels(["1×", "2×", "4×", "8×"])
h, l = axes[0].get_legend_handles_labels()
fig.legend(h, l, loc="lower center", ncol=5, frameon=False, fontsize=8, bbox_to_anchor=(0.5, -0.04))
fig.tight_layout(rect=(0, 0.08, 1, 1))
fig.savefig(os.path.join(PAPER, "figs", "fig_degraded.pdf"), bbox_inches="tight")
fig.savefig(os.path.join(PAPER, "figs", "fig_degraded.png"), dpi=200, bbox_inches="tight")

# table: slowdown at each level, range over sizes
names = {"perm_random": "Perm.\\ (random)", "perm_fullbis": "Perm.\\ (full-bis.)",
         "incast_random": "Incast (random)", "incast_remote": "Incast (remote)",
         "outcast_incast": "Outcast-incast"}
def rng(wl, stk, l):
    v = [d[(wl, s, stk)][l] / d[(wl, s, stk)]["base"] for s in (16, 64, 100)]
    a, b = min(v), max(v)
    return f"{a:.2f}" if abs(a - b) < 0.005 else f"{a:.2f}--{b:.2f}"
with open(os.path.join(PAPER, "degraded_table.tex"), "w") as f:
    # Writes the WHOLE tabular: \input inside a tabular breaks the \bottomrule
    # that follows it ("Misplaced \noalign"), so main.tex inputs this file
    # outside the alignment instead.
    f.write("% generated by bin/make_degraded_fig.py -- do not edit by hand\n")
    f.write("\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
            " & \\multicolumn{2}{c}{\\textbf{RoCE/DCQCN}} & \\multicolumn{2}{c}{\\textbf{UET}} \\\\\n"
            "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
            "\\textbf{Pattern} & 25\\% & 10\\% & 25\\% & 10\\% \\\\\n\\midrule\n")
    for wl, _, _ in WL:
        cells = [rng(wl, "ib", l) for l in ("r25", "r10")] + [rng(wl, "uet", l) for l in ("r25", "r10")]
        f.write(f"{names[wl]} & " + " & ".join(cells) + " \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(os.path.join(PAPER, "degraded_table.tex")).read())
for k in sorted(d):
    if k[1] == 16: print(k, {l: round(d[k][l]) for l in LEVELS})
